/** One generator: MCP tool surface, CLI help, plugin validator data, docs. */

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { REQUIRED_VERBS } from "./catalog.js";
import { buildContractMatrix, matrixStats } from "./matrix.js";
import { actionCount, allActionDefs } from "./registry.js";
import {
  ACTION_VERSION,
  PROTOCOL,
  REGISTRY_VERSION,
  RESULT_SCHEMA,
  VARIANT_SCHEMA_VERSION,
} from "./types.js";
import { variantSchemaDoc } from "./variant.js";
import { PRECONDITION_SCHEMA, PRESENTATION_SCHEMA } from "./envelope.js";

export const GENERATED_MARK = "AUTO-GENERATED by `npm run generate`. DO NOT EDIT.";

export function repoPaths(): { bridgeRoot: string; repoRoot: string } {
  const registryDir = path.dirname(fileURLToPath(import.meta.url));
  const bridgeRoot = path.resolve(registryDir, "..", "..");
  const repoRoot = path.resolve(bridgeRoot, "..");
  return { bridgeRoot, repoRoot };
}

function writeText(filePath: string, body: string): void {
  mkdirSync(path.dirname(filePath), { recursive: true });
  const text = body.endsWith("\n") ? body : `${body}\n`;
  writeFileSync(filePath, text, "utf8");
}

function jsonBlock(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

export function buildMcpTools(): Record<string, unknown> {
  const tools = Object.keys(REQUIRED_VERBS).map((group) => {
    const verbs = REQUIRED_VERBS[group];
    if (!verbs) {
      throw new Error(`missing group ${group}`);
    }
    return {
      name: `godot.${group}`,
      description: `Domain tool for ${group}.* actions. Discriminator is action.`,
      inputSchema: {
        type: "object",
        additionalProperties: false,
        required: ["action", "params"],
        properties: {
          action: { type: "string", enum: [...verbs] },
          params: {
            type: "object",
            description:
              "Per-action params. The matched ActionDef input_schema sets additionalProperties false.",
          },
          command_id: { type: "string", minLength: 26, maxLength: 26 },
          precondition: {
            type: "object",
            description: "Optional fingerprint/history/disk hash for E_CONFLICT.",
          },
          presentation: {
            type: "object",
            description: "Optional Watch/Fast presentation hint. Does not mutate the document.",
          },
        },
      },
    };
  });
  return {
    _generated: GENERATED_MARK,
    shape: "domain-tools-plus-action-discriminator",
    protocol: PROTOCOL,
    registry_version: REGISTRY_VERSION,
    action_version: ACTION_VERSION,
    tool_count: tools.length,
    action_count: actionCount(),
    tools,
  };
}

export function buildPluginValidator(): Record<string, unknown> {
  const actions: Record<string, unknown> = {};
  for (const def of allActionDefs()) {
    actions[def.id] = {
      method: def.method,
      verb: def.verb,
      action_version: def.action_version,
      side_effect: def.side_effect,
      undo: def.undo,
      timeout_ms: def.timeout_ms,
      cancellable: def.cancellable,
      required_policy: def.required_policy,
      checkpoint_required: def.checkpoint_required,
      input_schema: def.input_schema,
      output_schema: def.output_schema,
      error_codes: [...def.error_codes],
      postcondition: def.postcondition,
    };
  }
  return {
    _generated: GENERATED_MARK,
    protocol: PROTOCOL,
    registry_version: REGISTRY_VERSION,
    variant_schema: VARIANT_SCHEMA_VERSION,
    action_count: actionCount(),
    envelope: {
      allowed: [
        "protocol",
        "command_id",
        "method",
        "action",
        "params",
        "precondition",
        "presentation",
        "action_version",
      ],
      forbidden_client_fields: [
        "session_id",
        "actor",
        "actor_id",
        "project_id",
        "policy",
        "profile",
        "capability",
        "capability_grant",
        "grants",
      ],
      precondition: PRECONDITION_SCHEMA,
      presentation: PRESENTATION_SCHEMA,
    },
    result: RESULT_SCHEMA,
    variant: variantSchemaDoc(),
    actions,
  };
}

export function buildCliHelp(): string {
  const lines = [
    GENERATED_MARK,
    "",
    "hh-godot-bridge — action registry (not a live server)",
    `protocol: ${PROTOCOL}`,
    `registry: ${REGISTRY_VERSION}`,
    `actions: ${actionCount()}`,
    "shape: few domain tools + action discriminator (not one MCP tool per verb)",
    "",
    "Usage (schema-only):",
    "  npm run generate",
    "  npm run build",
    "",
    "Actions:",
  ];
  for (const def of allActionDefs()) {
    lines.push(
      `  ${def.id.padEnd(28)} ${def.side_effect.padEnd(12)} ${def.undo.padEnd(22)} ${def.required_policy.padEnd(16)} ${def.postcondition}`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

export function buildActionsMarkdown(): string {
  const rows = [
    `# Action catalog`,
    ``,
    `> ${GENERATED_MARK}`,
    ``,
    `Source: \`bridge/src/registry/\`. ${actionCount()} actions. Protocol \`${PROTOCOL}\`.`,
    `MCP surface is **few domain tools + action discriminator**, not one tool per verb.`,
    ``,
    `| id | method | side_effect | undo | policy | timeout_ms | cancellable | checkpoint | postcondition |`,
    `| --- | --- | --- | --- | --- | ---: | --- | --- | --- |`,
  ];
  for (const def of allActionDefs()) {
    rows.push(
      `| ${def.id} | ${def.method} | ${def.side_effect} | ${def.undo} | ${def.required_policy} | ${def.timeout_ms} | ${def.cancellable} | ${def.checkpoint_required} | ${def.postcondition} |`,
    );
  }
  rows.push("");
  return rows.join("\n");
}

export function buildContractMatrixMarkdown(): string {
  const cases = buildContractMatrix();
  const stats = matrixStats(cases);
  const rows = [
    `# Contract matrix`,
    ``,
    `> ${GENERATED_MARK}`,
    ``,
    `Executed by \`tests/bootstrap/test_registry.py\` via the registry (not printed-only).`,
    `Actions: ${stats.actions}. Cases: ${cases.length} ` +
      `(positive=${stats.positives} missing=${stats.missing} unknown=${stats.unknown} type=${stats.type} bounds=${stats.bounds}).`,
    `\`capabilities.describe\` expands 4-way invalid + 1 positive **per kind** ` +
      `(version, class, property, method, action).`,
    ``,
    `| id | action | kind | lane | expect | params |`,
    `| --- | --- | --- | --- | --- | --- |`,
  ];
  for (const c of cases) {
    const params = JSON.stringify(c.params).replace(/\|/g, "\\|");
    rows.push(
      `| ${c.id} | ${c.action_id} | ${c.kind || "—"} | ${c.lane} | ${c.expect} | \`${params}\` |`,
    );
  }
  rows.push("");
  return rows.join("\n");
}

export function generatedTargets(): { rel: string; body: string }[] {
  const { bridgeRoot, repoRoot } = repoPaths();
  return [
    {
      rel: path.relative(repoRoot, path.join(bridgeRoot, "generated", "mcp-tools.json")),
      body: jsonBlock(buildMcpTools()),
    },
    {
      rel: path.relative(repoRoot, path.join(bridgeRoot, "generated", "cli-help.txt")),
      body: buildCliHelp(),
    },
    {
      rel: path.relative(repoRoot, path.join(bridgeRoot, "generated", "plugin-validator.json")),
      body: jsonBlock(buildPluginValidator()),
    },
    {
      rel: path.relative(repoRoot, path.join(repoRoot, "docs", "godot-agent", "ACTIONS.md")),
      body: buildActionsMarkdown(),
    },
    {
      rel: path.relative(repoRoot, path.join(repoRoot, "docs", "godot-agent", "CONTRACT_MATRIX.md")),
      body: buildContractMatrixMarkdown(),
    },
  ].map((row) => ({
    rel: row.rel.replace(/\\/g, "/"),
    body: row.body,
  }));
}

function buildPluginActionsJson(): string {
  const actions: Record<string, unknown> = {};
  for (const def of allActionDefs()) {
    const required = Array.isArray(def.input_schema.required) ? def.input_schema.required : [];
    actions[def.id] = {
      method: def.method,
      verb: def.verb,
      side_effect: def.side_effect,
      timeout_ms: def.timeout_ms,
      required,
      postcondition: def.postcondition,
      checkpoint_required: def.checkpoint_required,
    };
  }
  return jsonBlock({
    source: "bridge/generated/plugin-validator.json",
    protocol: PROTOCOL,
    envelope: {
      allowed: [
        "protocol",
        "command_id",
        "method",
        "action",
        "params",
        "precondition",
        "presentation",
        "action_version",
      ],
      forbidden_client_fields: [
        "session_id",
        "actor",
        "actor_id",
        "project_id",
        "policy",
        "profile",
        "capability",
        "capability_grant",
        "grants",
      ],
    },
    noop: {
      method: "hh.plugin",
      action: "noop",
      side_effect: "read",
      timeout_ms: 5000,
    },
    actions,
  });
}

export function writeGeneratedArtifacts(): string[] {
  const { repoRoot } = repoPaths();
  const written: string[] = [];
  for (const target of generatedTargets()) {
    const abs = path.join(repoRoot, target.rel);
    writeText(abs, target.body);
    written.push(target.rel);
  }
  const pluginActionsRel = "godot/plugin-project/addons/hh_agent/core/actions.json";
  writeText(path.join(repoRoot, pluginActionsRel), buildPluginActionsJson());
  written.push(pluginActionsRel);
  return written;
}
