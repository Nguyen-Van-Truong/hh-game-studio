def _blit(
    canvas: bytearray,
    cw: int,
    x0: int,
    y0: int,
    src_w: int,
    src_h: int,
    src: bytes,
    scale: int,
) -> None:
    for y in range(src_h):
        for x in range(src_w):
            i = (y * src_w + x) * 4
            r, g, b, a = src[i : i + 4]
            if a == 0:
                continue
            for dy in range(scale):
                for dx in range(scale):
                    px = x0 + x * scale + dx
                    py = y0 + y * scale + dy
                    j = (py * cw + px) * 4
                    canvas[j : j + 4] = bytes((r, g, b, 255))


def _draw_label(canvas: bytearray, cw: int, x0: int, y0: int, text: str) -> None:
    ink = (32, 32, 32, 255)
    x = x0
    for ch in text.lower():
        glyph = _FONT_3X5.get(ch)
        if glyph is None:
            x += 4
            continue
        for gy, row in enumerate(glyph):
            for gx, cell in enumerate(row):
                if cell == "#":
                    j = ((y0 + gy) * cw + (x + gx)) * 4
                    if 0 <= x + gx < cw:
                        canvas[j : j + 4] = bytes(ink)
        x += 4


def write_contact_sheet(rendered: list[tuple[dict, bytes]]) -> None:
    scale = 4
    cols = 8
    cell_w = 136
    cell_h = 148
    rows = (len(rendered) + cols - 1) // cols
    pad = 8
    cw = pad * 2 + cols * cell_w
    ch = pad * 2 + rows * cell_h
    bg = (128, 128, 128, 255)
    canvas = bytearray(bg * (cw * ch))
    for i, (sprite, rgba) in enumerate(rendered):
        col = i % cols
        row = i // cols
        x0 = pad + col * cell_w
        y0 = pad + row * cell_h
        sw, sh = sprite["w"], sprite["h"]
        # center the 4x sprite in the cell, leave room for the label
        px = x0 + (cell_w - sw * scale) // 2
        py = y0 + 4
        _blit(canvas, cw, px, py, sw, sh, rgba, scale)
        label = sprite["dest_name"].replace(".png", "")
        _draw_label(canvas, cw, x0 + 4, y0 + cell_h - 10, label[:16])
    write_png(CONTACT_PATH, cw, ch, bytes(canvas))


