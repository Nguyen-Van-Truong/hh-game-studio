SPRITES: list[dict] = []


def _add(
    asset_id: str,
    dest_name: str,
    w: int,
    h: int,
    palette: dict,
    ascii_map: str,
) -> None:
    SPRITES.append(
        {
            "asset_id": asset_id,
            "dest_rel": f"assets/{dest_name}",
            "dest_name": dest_name,
            "w": w,
            "h": h,
            "palette": palette,
            "ascii_map": ascii_map,
        }
    )


