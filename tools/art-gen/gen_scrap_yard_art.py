# ---------------------------------------------------------------------------
# PNG I/O (stdlib only)
# ---------------------------------------------------------------------------


def _chunk(tag: bytes, data: bytes) -> bytes:
    crc = zlib.crc32(tag + data) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)


def write_png(path: Path, w: int, h: int, rgba: bytes) -> None:
    if len(rgba) != w * h * 4:
        raise ValueError(f"{path}: pixel buffer {len(rgba)} != {w}*{h}*4")
    raw = bytearray()
    stride = w * 4
    for y in range(h):
        raw.append(0)
        raw.extend(rgba[y * stride : (y + 1) * stride])
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    blob = PNG_MAGIC + _chunk(b"IHDR", ihdr)
    blob += _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    blob += _chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(blob)


def _paeth(a: int, b: int, c: int) -> int:
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def read_png(path: Path) -> tuple[int, int, bytes]:
    data = path.read_bytes()
    if data[:8] != PNG_MAGIC:
        raise ValueError(f"{path} is not a PNG")
    pos = 8
    width = height = None
    idat = bytearray()
    while pos + 8 <= len(data):
        (length,) = struct.unpack(">I", data[pos : pos + 4])
        tag = data[pos + 4 : pos + 8]
        chunk = data[pos + 8 : pos + 8 + length]
        pos += 12 + length
        if tag == b"IHDR":
            width, height, bit, color, comp, filt, inter = struct.unpack(
                ">IIBBBBB", chunk
            )
            if (bit, color, comp, filt, inter) != (8, 6, 0, 0, 0):
                raise ValueError(f"{path}: unsupported IHDR")
        elif tag == b"IDAT":
            idat.extend(chunk)
        elif tag == b"IEND":
            break
    if width is None or height is None:
        raise ValueError(f"{path}: missing IHDR")
    raw = zlib.decompress(bytes(idat))
    stride = width * 4
    expected = height * (1 + stride)
    if len(raw) != expected:
        raise ValueError(f"{path}: bad IDAT size {len(raw)} != {expected}")
    out = bytearray(height * stride)
    prev = bytes(stride)
    for y in range(height):
        ftype = raw[y * (1 + stride)]
        row = bytearray(raw[y * (1 + stride) + 1 : (y + 1) * (1 + stride)])
        if ftype == 0:
            pass
        elif ftype == 1:
            for i in range(stride):
                left = row[i - 4] if i >= 4 else 0
                row[i] = (row[i] + left) & 255
        elif ftype == 2:
            for i in range(stride):
                row[i] = (row[i] + prev[i]) & 255
        elif ftype == 3:
            for i in range(stride):
                left = row[i - 4] if i >= 4 else 0
                row[i] = (row[i] + ((left + prev[i]) // 2)) & 255
        elif ftype == 4:
            for i in range(stride):
                left = row[i - 4] if i >= 4 else 0
                upleft = prev[i - 4] if i >= 4 else 0
                row[i] = (row[i] + _paeth(left, prev[i], upleft)) & 255
        else:
            raise ValueError(f"{path}: filter {ftype}")
        out[y * stride : (y + 1) * stride] = row
        prev = bytes(row)
    return width, height, bytes(out)


# ---------------------------------------------------------------------------
# Rasterise ASCII maps
# ---------------------------------------------------------------------------


def parse_map(text: str, w: int, h: int, name: str) -> list[str]:
    lines = text.strip("\n").split("\n")
    if len(lines) != h:
        raise ValueError(f"{name}: expected {h} rows, got {len(lines)}")
    for i, line in enumerate(lines):
        if len(line) != w:
            raise ValueError(
                f"{name}: row {i} has {len(line)} cols, expected {w}: {line!r}"
            )
    return lines


def rasterise(sprite: dict) -> bytes:
    name = sprite["dest_name"]
    w, h = sprite["w"], sprite["h"]
    palette = sprite["palette"]
    rows = parse_map(sprite["ascii_map"], w, h, name)
    out = bytearray()
    for line in rows:
        for ch in line:
            if ch == ".":
                out.extend((0, 0, 0, 0))
                continue
            if ch not in palette:
                raise ValueError(f"{name}: unknown palette char {ch!r}")
            out.extend(palette[ch])
    return bytes(out)


def lowest_opaque_row(w: int, h: int, rgba: bytes) -> int | None:
    last = None
    for y in range(h):
        for x in range(w):
            if rgba[(y * w + x) * 4 + 3] != 0:
                last = y
                break
    return last


def has_transparent(w: int, h: int, rgba: bytes) -> bool:
    for i in range(0, w * h * 4, 4):
        if rgba[i + 3] == 0:
            return True
    return False


def edges_match(w: int, h: int, rgba: bytes) -> tuple[bool, bool]:
    col_ok = True
    row_ok = True
    for y in range(h):
        a = rgba[(y * w + 0) * 4 : (y * w + 1) * 4]
        b = rgba[(y * w + (w - 1)) * 4 : (y * w + w) * 4]
        if a != b:
            col_ok = False
            break
    for x in range(w):
        a = rgba[(0 * w + x) * 4 : (0 * w + x + 1) * 4]
        b = rgba[((h - 1) * w + x) * 4 : ((h - 1) * w + x + 1) * 4]
        if a != b:
            row_ok = False
            break
    return col_ok, row_ok


