def main() -> int:
    if [s["asset_id"] for s in SPRITES] != sorted(s["asset_id"] for s in SPRITES):
        raise SystemExit("asset ids must be listed in ascending order")
    if len(SPRITES) != 27:
        raise SystemExit(f"expected 27 sprites, got {len(SPRITES)}")

    ASSETS_DIR.mkdir(parents=True, exist_ok=True)
    rendered: list[tuple[dict, bytes]] = []
    print(f"{'path':<40} {'w':>4} {'h':>4} {'bytes':>8}")
    print("-" * 60)
    for sprite in SPRITES:
        rgba = rasterise(sprite)
        dest = ASSETS_DIR / sprite["dest_name"]
        write_png(dest, sprite["w"], sprite["h"], rgba)
        rendered.append((sprite, rgba))

    index = {
        "assets": [
            {"asset_id": s["asset_id"], "dest_rel": s["dest_rel"]} for s in SPRITES
        ]
    }
    INDEX_PATH.write_text(json.dumps(index, separators=(",", ":")) + "\n", encoding="utf-8")

    # verify on-disk
    print()
    print("ON-DISK VERIFY")
    print(f"{'path':<40} {'w':>4} {'h':>4} {'bytes':>8}")
    print("-" * 60)
    for sprite in SPRITES:
        dest = ASSETS_DIR / sprite["dest_name"]
        raw = dest.read_bytes()
        if raw[:8] != PNG_MAGIC:
            raise SystemExit(f"{dest} missing PNG magic")
        w, h, pixels = read_png(dest)
        if (w, h) != (sprite["w"], sprite["h"]):
            raise SystemExit(f"{dest} size {w}x{h} != {sprite['w']}x{sprite['h']}")
        rel = dest.relative_to(REPO_ROOT).as_posix()
        print(f"{rel:<40} {w:>4} {h:>4} {len(raw):>8}")

    print()
    print("TILING (col0==col w-1, row0==row h-1)")
    for name in (
        "tile_floor.png",
        "tile_wall.png",
        "tile_plat.png",
        "ladder.png",
        "bg_panel.png",
    ):
        dest = ASSETS_DIR / name
        w, h, pixels = read_png(dest)
        col_ok, row_ok = edges_match(w, h, pixels)
        print(f"  {name:<18} left-right={'OK' if col_ok else 'FAIL'}  top-bottom={'OK' if row_ok else 'FAIL'}")
        if not (col_ok and row_ok):
            raise SystemExit(f"{name} is not seamless")

    print()
    print("CHARACTER ALPHA / FEET")
    for sprite, rgba in rendered:
        if sprite["dest_name"] not in CHAR_SPRITES:
            continue
        w, h = sprite["w"], sprite["h"]
        trans = has_transparent(w, h, rgba)
        low = lowest_opaque_row(w, h, rgba)
        feet = low == h - 1
        print(
            f"  {sprite['dest_name']:<18} transparent={'OK' if trans else 'FAIL'}  "
            f"lowest_opaque={low}  feet={'OK' if feet else 'FAIL'}"
        )
        if not trans or not feet:
            raise SystemExit(f"{sprite['dest_name']} failed character checks")

    write_contact_sheet(rendered)
    print()
    print(f"wrote {INDEX_PATH.relative_to(REPO_ROOT).as_posix()}")
    print(f"wrote {CONTACT_PATH.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
