def convert(map_id: str, spec: dict) -> dict:
    rows = spec["rows"]
    height = len(rows)
    width = len(rows[0])
    theme = spec["theme"]
    solid: list[list[int]] = []
    one_way: list[list[int]] = []
    ladder: list[list[int]] = []
    hazard: list[list[int]] = []
    prop: list[list[int]] = []
    spawn: list[list[int]] = []
    pickup: list[list[int]] = []
    for y, row in enumerate(rows):
        if len(row) != width:
            raise SystemExit(f"{map_id} row {y} width {len(row)} != {width}")
        for x, ch in enumerate(row):
            if ch == "#":
                solid.append([x, y])
            elif ch == "=":
                one_way.append([x, y])
            elif ch == "H":
                ladder.append([x, y])
            elif ch == "L":
                ladder.append([x, y])
                one_way.append([x, y])
            elif ch == "c":
                prop.append([x, y])
            elif ch == "b":
                hazard.append([x, y])
            elif ch == "P":
                spawn.append([x, y, 0])
            elif ch == "1":
                spawn.append([x, y, 1])
            elif ch == "2":
                spawn.append([x, y, 2])
            elif ch == "3":
                spawn.append([x, y, 3])
            elif ch == "w":
                pickup.append([x, y])
            elif ch != ".":
                raise SystemExit(f"{map_id} unknown char {ch!r} at {x},{y}")
    if map_id == "police":
        for cell in ([26, 7], [50, 7], [50, 2]):
            if cell not in one_way:
                one_way.append(cell)
    doc = {
        "schema": "vf.maps.layers.v1",
        "schema_version": 1,
        "title": "Vault Fighters",
        "id": map_id,
        "display_name": spec["display_name"],
        "width": width,
        "height": height,
        "tile": 16,
        "theme": theme,
        "y8_parity_claimed": False,
        "original_exact_numbers_claimed": False,
        "values_are_tuning": True,
        "ascii_source_retired": True,
        "live_c_b_tiles": True,
        "layers": {
            "solid": solid,
            "one_way": one_way,
            "ladder": ladder,
            "hazard": hazard,
            "prop": prop,
            "spawn": spawn,
            "pickup": pickup,
        },
    }
    return doc


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for map_id, spec in MAPS.items():
        doc = convert(map_id, spec)
        path = OUT / f"{map_id}.json"
        path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} w={doc['width']} h={doc['height']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
